-- 19. REVIEWS — đánh giá, luôn gắn với booking THẬT (1 booking → tối đa 1 review)
--     Backend chỉ cho review khi: bookings.status = 'checkout'
--     AND bookings.customer_id = user đang đăng nhập.
--     "Verified stay" suy ra từ booking, không cần cột riêng.
-- ═════════════════════════════════════════════════════════════════════════
CREATE TABLE IF NOT EXISTS public.reviews (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id            BIGINT NOT NULL,
    customer_id           BIGINT NOT NULL,
    unit_id               BIGINT NOT NULL,

    overall_rating        SMALLINT NOT NULL CHECK (overall_rating BETWEEN 1 AND 5),
    cleanliness_rating    SMALLINT NOT NULL CHECK (cleanliness_rating BETWEEN 1 AND 5),
    location_rating       SMALLINT NOT NULL CHECK (location_rating BETWEEN 1 AND 5),
    amenities_rating      SMALLINT NOT NULL CHECK (amenities_rating BETWEEN 1 AND 5),
    accuracy_rating       SMALLINT NOT NULL CHECK (accuracy_rating BETWEEN 1 AND 5),
    communication_rating  SMALLINT NOT NULL CHECK (communication_rating BETWEEN 1 AND 5),
    value_rating          SMALLINT NOT NULL CHECK (value_rating BETWEEN 1 AND 5),

    title                 VARCHAR(255),
    comment               TEXT,

    status                TEXT NOT NULL DEFAULT 'pending'
                          CONSTRAINT chk_reviews_status CHECK (status IN ('pending','approved','rejected')),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    approved_at           TIMESTAMPTZ,
    approved_by_admin_id  BIGINT,

    CONSTRAINT uq_reviews_booking UNIQUE (booking_id),
    CONSTRAINT fk_reviews_booking FOREIGN KEY (booking_id)
        REFERENCES public.bookings (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reviews_customer FOREIGN KEY (customer_id)
        REFERENCES public.customers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reviews_unit FOREIGN KEY (unit_id)
        REFERENCES public.units (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reviews_admin FOREIGN KEY (approved_by_admin_id)
        REFERENCES public.admins (id) ON DELETE SET NULL
);

