-- 24. AUDIT_LOGS — nhật ký thao tác admin
--     old_value_json / new_value_json dùng JSONB
-- ═════════════════════════════════════════════════════════════════════════
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id       BIGINT,
    action         VARCHAR(50) NOT NULL,            -- CHANGE_BOOKING_STATUS|UPDATE_UNIT_PRICE|BLOCK_DATES|...
    entity_type    VARCHAR(30) NOT NULL,
    entity_id      BIGINT,
    old_value_json JSONB,
    new_value_json JSONB,
    ip_address     VARCHAR(45),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_audit_logs_admin FOREIGN KEY (admin_id)
        REFERENCES public.admins (id) ON DELETE SET NULL
);

