-- YANGHOMESTAY — POSTGRESQL / SUPABASE SCHEMA (PHASE 2 — SUPABASE ADAPTATION)
--
-- • Chạy trong Supabase SQL Editor (Project → SQL Editor → New query).
-- • Kiến trúc: PROPERTY → UNIT → AVAILABILITY → BOOKING (giống Phase 2 MySQL).
-- • Không cần CREATE DATABASE — Supabase cấp sẵn database; tables tạo trong schema `public`.
-- • Chạy theo thứ tự: 001_schema.sql → 002_seed.sql → 003_indexes.sql
--                       → 004_rls.sql → 005_functions.sql
--
-- QUY ƯỚC NGÀY THÁNG (toàn hệ thống):
--   • check_in  = inclusive (đêm đầu được tính)
--   • check_out = exclusive (không tính đêm cuối)
--   • Ví dụ: 20/08 → 23/08 = 3 đêm (20, 21, 22); khách mới nhận phòng được từ 23/08
--
-- QUY ƯỚC TIỀN TỆ:
--   • Giá lưu bằng VND nguyên (BIGINT), KHÔNG dùng "850" để ám chỉ 850.000.
--
-- GHI CHÚ CHUYỂN ĐỔI TỪ MYSQL:
--   AUTO_INCREMENT          → BIGINT GENERATED BY DEFAULT AS IDENTITY
--   UNSIGNED                → bỏ (dùng CHECK >= 0)
--   TINYINT(1)              → BOOLEAN
--   ENUM(...)               → TEXT + CHECK (linh hoạt, dễ mở rộng)
--   TIMESTAMP               → TIMESTAMPTZ
--   JSON                    → JSONB
--   ON UPDATE CURRENT_TIMESTAMP → trigger set_updated_at() (xem 005_functions.sql)
--   ENGINE=InnoDB, backticks → bỏ
-- ═════════════════════════════════════════════════════════════════════════

