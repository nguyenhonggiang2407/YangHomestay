    type        VARCHAR(40) NOT NULL,
    title       VARCHAR(150) NOT NULL,
    message     VARCHAR(500),
    entity_type VARCHAR(30),                        -- vd: booking, unit, review
    entity_id   BIGINT,
    is_read     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at     TIMESTAMPTZ,
    CONSTRAINT fk_notifications_customer FOREIGN KEY (customer_id)
        REFERENCES public.customers (id) ON DELETE CASCADE,
    CONSTRAINT fk_notifications_admin FOREIGN KEY (admin_id)
        REFERENCES public.admins (id) ON DELETE CASCADE
