    discount_value           BIGINT NOT NULL CHECK (discount_value >= 0),  -- % hoặc số tiền VND
    minimum_booking_value    BIGINT CHECK (minimum_booking_value IS NULL OR minimum_booking_value >= 0),
    maximum_discount         BIGINT CHECK (maximum_discount IS NULL OR maximum_discount >= 0),  -- trần chiết khấu (áp dụng cho %)
    valid_from               DATE NOT NULL,
    valid_until              DATE NOT NULL,
    usage_limit              INTEGER CHECK (usage_limit IS NULL OR usage_limit >= 0),
    usage_limit_per_customer INTEGER CHECK (usage_limit_per_customer IS NULL OR usage_limit_per_customer >= 0),
    active                   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_promotions_code UNIQUE (code),
    CONSTRAINT chk_promotions_dates CHECK (valid_until >= valid_from)
);

-- ═════════════════════════════════════════════════════════════════════════
-- 14. BOOKINGS — bảng quan trọng nhất
--     • check_in inclusive / check_out exclusive (20/08 → 23/08 = 3 đêm)
--     • Overlap: new_check_in < existing_check_out AND new_check_out > existing_check_in
--       chỉ xét status: pending, confirmed, checkin (cancelled/checkout không chặn)
--     • subtotal = tổng booking_nights; total = subtotal + cleaning_fee − discount_amount
--     • booking_reference do backend Phase 3 generate (vd: YH202608160001)
-- ═════════════════════════════════════════════════════════════════════════
CREATE TABLE IF NOT EXISTS public.bookings (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference       VARCHAR(20)  NOT NULL,
    customer_id             BIGINT NOT NULL,
    unit_id                 BIGINT NOT NULL,

    guest_name              VARCHAR(100) NOT NULL,  -- snapshot tại thời điểm đặt
    guest_email             VARCHAR(100),
    guest_phone             VARCHAR(20),

    check_in                DATE NOT NULL,          -- inclusive
    check_out               DATE NOT NULL,          -- exclusive
    number_of_nights        SMALLINT NOT NULL CHECK (number_of_nights > 0),

    adults                  SMALLINT NOT NULL DEFAULT 1 CHECK (adults > 0),
    children                SMALLINT NOT NULL DEFAULT 0 CHECK (children >= 0),
    total_guests            SMALLINT NOT NULL DEFAULT 1 CHECK (total_guests > 0),

    subtotal                BIGINT NOT NULL CHECK (subtotal >= 0),      -- = SUM(booking_nights.nightly_rate)
    cleaning_fee            BIGINT NOT NULL DEFAULT 0 CHECK (cleaning_fee >= 0),
    discount_amount         BIGINT NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    total_amount            BIGINT NOT NULL CHECK (total_amount >= 0),  -- = subtotal + cleaning_fee − discount_amount
    currency                CHAR(3) NOT NULL DEFAULT 'VND',

    promotion_id            BIGINT,
    promotion_code_snapshot VARCHAR(40),             -- lưu mã promo tại thời điểm đặt

    status                  TEXT NOT NULL DEFAULT 'pending'
                            CONSTRAINT chk_bookings_status CHECK (status IN ('pending','confirmed','checkin','checkout','cancelled')),
    payment_status          TEXT NOT NULL DEFAULT 'unpaid'
                            CONSTRAINT chk_bookings_payment_status CHECK (payment_status IN ('unpaid','partial','paid','refunded')),

    special_requests        TEXT,
    cancellation_reason     VARCHAR(500),

    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    confirmed_at            TIMESTAMPTZ,
    checked_in_at           TIMESTAMPTZ,
    checked_out_at          TIMESTAMPTZ,
    cancelled_at            TIMESTAMPTZ,

    CONSTRAINT uq_bookings_reference UNIQUE (booking_reference),
    CONSTRAINT chk_bookings_dates CHECK (check_out > check_in),
    CONSTRAINT fk_bookings_customer FOREIGN KEY (customer_id)
        REFERENCES public.customers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bookings_unit FOREIGN KEY (unit_id)
        REFERENCES public.units (id) ON DELETE RESTRICT,
    CONSTRAINT fk_bookings_promotion FOREIGN KEY (promotion_id)
        REFERENCES public.promotions (id) ON DELETE SET NULL
);

COMMENT ON TABLE public.bookings IS 'Đặt phòng — bảng trung tâm. Lịch sử booking phải được giữ (RESTRICT + soft disable)';

