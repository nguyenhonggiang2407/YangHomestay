-- 20. NEARBY_PLACES — địa điểm lân cận (Yang Hanoi Guide / Map / Itinerary)
--     distance_meters / walking_minutes: dữ liệu THẬT khi có, demo phải đánh dấu rõ.
-- ═════════════════════════════════════════════════════════════════════════
CREATE TABLE IF NOT EXISTS public.nearby_places (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_id       BIGINT NOT NULL,
    name              VARCHAR(150) NOT NULL,
    category          TEXT NOT NULL DEFAULT 'attraction'
                      CONSTRAINT chk_nearby_places_category CHECK (category IN ('food','coffee','attraction','nightlife','shopping','photography','transport')),
    short_description VARCHAR(255),
    latitude          NUMERIC(10,7),
    longitude         NUMERIC(10,7),
    distance_meters   INTEGER CHECK (distance_meters IS NULL OR distance_meters >= 0),
    walking_minutes   SMALLINT CHECK (walking_minutes IS NULL OR walking_minutes >= 0),
    image_url         VARCHAR(255),
    featured          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_nearby_places_property FOREIGN KEY (property_id)
        REFERENCES public.properties (id) ON DELETE CASCADE
);

