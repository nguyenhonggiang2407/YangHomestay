-- ═════════════════════════════════════════════════════════════════════════
-- 12. RATE_RULES — luật giá linh hoạt (weekday / weekend / holiday / seasonal)
--     • day_of_week: 1=Chủ nhật ... 7=Thứ 7 (GIỮ NGUYÊN quy ước như MySQL DAYOFWEEK),
--       NULL = mọi ngày. Lưu ý: EXTRACT(DOW FROM d) của PostgreSQL trả 0-6 (0=CN),
--       nên backend dùng EXTRACT(DOW FROM d) + 1 để ra đúng quy ước lưu trữ này.
--     • start_date / end_date: NULL = không giới hạn
--     • Nếu overlap: priority cao hơn thắng; cùng priority → rule cụ thể hơn thắng
-- ═════════════════════════════════════════════════════════════════════════
CREATE TABLE IF NOT EXISTS public.rate_rules (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id     BIGINT NOT NULL,
    name        VARCHAR(150) NOT NULL,             -- vd: Cuối tuần Thứ 7
    start_date  DATE,
    end_date    DATE,
    day_of_week SMALLINT CHECK (day_of_week BETWEEN 1 AND 7),  -- 1=CN ... 7=T7, NULL = mọi ngày
    price       BIGINT NOT NULL CHECK (price >= 0),
    priority    SMALLINT NOT NULL DEFAULT 0,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_rate_rules_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date > start_date),
    CONSTRAINT fk_rate_rules_unit FOREIGN KEY (unit_id)
        REFERENCES public.units (id) ON DELETE CASCADE
);

